const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://localhost:3000';
const api = process.env.API_TEST_URL || 'http://127.0.0.1:8080';
const out = process.env.UI_TEST_OUTPUT || path.join(__dirname, '../../.ui-qa');
fs.mkdirSync(out, { recursive: true });
const terms = ['raw_material', 'production', 'setup', 'overtime', 'finished_goods_holding', 'raw_material_holding', 'shortage', 'safety_stock_gap', 'service_target_violation'];
let browser;
(async () => {
  browser = await chromium.launch({ channel: process.env.UI_BROWSER || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  let healthy = false;
  for (let i = 0; i < 90 && !healthy; i++) {
    try { healthy = (await page.request.get(api + '/api/health', { timeout: 2000 })).ok(); } catch {}
    if (!healthy) await new Promise(resolve => setTimeout(resolve, 1000));
  }
  assert(healthy, 'Backend must be ready');
  await page.goto(base + '/?view=lab');
  await page.getByText('Engine connected', { exact: true }).waitFor({ timeout: 60000 });
  await page.getByRole('button', { name: 'Apply priorities', exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('.objective-priorities .button').disabled);
  assert.equal(await page.locator('.objective-weight-row').count(), 9);
  const weight = name => page.getByRole('spinbutton', { name: name + ' weight', exact: true });
  assert.equal(await weight('Unserved demand / shortage').inputValue(), '1');
  const baselineOperating = await page.getByTestId('objective-operating-cost').textContent();
  await weight('Raw-material purchases').fill('20');
  await weight('Unserved demand / shortage').fill('0');
  await weight('Below service-level target').fill('0');
  await weight('Below safety-stock target').fill('0');
  await page.getByText('Changes not applied', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Save snapshot', exact: true }).isDisabled());
  assert.equal(await page.getByTestId('applied-weight-shortage').textContent(), '1×', 'Old applied result stays visible');
  const run = async () => {
    const pending = page.waitForResponse(r => r.url().includes('/api/v1/optimization/demo') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Apply priorities', exact: true }).click();
    const response = await pending; assert.equal(response.status(), 200);
    const body = await response.json();
    await page.getByText('Results match current inputs', { exact: true }).waitFor();
    return body;
  };
  const changed = await run();
  assert.equal(changed.input.objective_weights.raw_material, 20);
  assert.equal(changed.selected_plan.objective_weights.shortage, 0);
  assert.equal(await page.getByTestId('applied-weight-shortage').textContent(), '0×');
  assert.notEqual(await page.getByTestId('objective-operating-cost').textContent(), baselineOperating);
  assert(!(await page.getByTestId('objective-score').textContent()).includes('$'));
  assert(changed.selected_plan.expected_shortage_tons > 0, 'Zero risk weights may sacrifice service');
  assert.equal(await page.locator('.objective-scorecard tbody tr').count(), 9);
  await page.getByRole('button', { name: 'Save snapshot', exact: true }).click();
  await page.locator('nav').getByRole('button', { name: 'Saved plans', exact: true }).click();
  await page.getByRole('button', { name: 'Open', exact: true }).click();
  assert.equal(await weight('Raw-material purchases').inputValue(), '20');
  assert.equal(await weight('Unserved demand / shortage').inputValue(), '0');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export plan', exact: true }).click();
  const download = await downloadEvent;
  const exported = JSON.parse(fs.readFileSync(await download.path(), 'utf8'));
  assert.equal(exported.input.objective_weights.raw_material, 20);
  assert.equal(exported.selected_plan.objective_weights.shortage, 0);
  for (const slider of await page.locator('.objective-weight-row input[type=number]').all()) await slider.fill('0');
  assert(await page.getByRole('button', { name: 'Apply priorities', exact: true }).isDisabled());
  await page.getByRole('alert').filter({ hasText: 'At least one weight' }).waitFor();
  const invalid = await page.request.post(api + '/api/v1/optimization/demo', { data: { ...changed.input, objective_weights: Object.fromEntries(terms.map(key => [key, 0])) } });
  assert.equal(invalid.status(), 422);
  await page.getByRole('button', { name: 'Reset objective weights to 1', exact: true }).click();
  assert.equal(await weight('Raw-material purchases').inputValue(), '1');
  await page.getByRole('button', { name: 'Delivery priority', exact: true }).click();
  const delivery = await run();
  assert.equal(delivery.selected_plan.objective_weights.shortage, 5);
  await page.waitForTimeout(300);
  await page.screenshot({ path: path.join(out, 'objective-weights-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No page-level overflow');
  assert.equal(await weight('Unserved demand / shortage').inputValue(), '5');
  await page.screenshot({ path: path.join(out, 'objective-weights-mobile.png'), fullPage: true });
  await page.locator('.objective-priorities').screenshot({ path: path.join(out, 'objective-controls-mobile.png') });
  const oldInput = { ...delivery.input }; delete oldInput.objective_weights;
  const legacy = await page.request.post(api + '/api/v1/optimization/demo', { data: oldInput });
  assert.equal(legacy.status(), 200);
  assert.equal((await legacy.json()).selected_plan.objective_weights.shortage, 1);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', weightControls: 9, solverDecisionsChange: true, moneySeparateFromScore: true, saveRestoreExport: true, allZeroRejected: true, legacyRequests: true, desktopMobile: true, errors }));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
