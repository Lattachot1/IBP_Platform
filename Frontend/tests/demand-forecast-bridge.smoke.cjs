const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://localhost:3000';
const api = process.env.API_TEST_URL || 'http://127.0.0.1:8080';
const out = process.env.UI_TEST_OUTPUT || path.join(__dirname, '../../.ui-qa');
fs.mkdirSync(out, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ channel: process.env.UI_BROWSER || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 }, timezoneId: 'Asia/Bangkok' });
  page.setDefaultTimeout(60000);
  const errors = [], solveRequests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/planning/integrated')) solveRequests.push(r.postDataJSON()); });
  await page.goto(base + '/?view=integrated');
  await page.getByText('Inputs ready / no joint plan solved yet', { exact: true }).waitFor();
  const status = await (await page.request.get(api + '/api/v1/planning/demand-forecast/status')).json();
  assert.equal(status.models.length, 4, 'Use the real four-grade billing-trained engine for this local integration test');
  assert.deepEqual(status.manual_grades, ['BR150B', 'BR360B']);
  const original = await (await page.request.get(api + '/api/v1/planning/pilot?horizon_days=7')).json();
  original.plant.start_date = status.earliest_common_month + '-01';
  original.plant.time_limit_s = 5;
  original.plant.initial = { grade: 'BR150', remain_days: 7, rx12_age: 0, rx34_age: 0, vcr_elapsed_days: 0 };
  original.opening_raw_tons = 2000;
  for (const g of Object.keys(original.firm_demand)) original.firm_demand[g] = Array(7).fill(0);
  original.firm_demand.BR150[0] = 100;
  original.firm_demand.BR150B[0] = 10;
  const imported = page.waitForResponse(r => r.url().endsWith('/planning/validate') && r.request().method() === 'POST');
  await page.locator('.joint-pilot input[type=file]').setInputFiles({ name: 'bridge-test-input.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) });
  assert.equal((await imported).status(), 200);
  const load = async () => {
    const pending = page.waitForResponse(r => r.url().endsWith('/planning/demand-forecast') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Load real demand forecast', exact: true }).click();
    const response = await pending; assert.equal(response.status(), 200);
    return response.json();
  };
  const loaded = await load();
  assert.equal(solveRequests.length, 0, 'Load changes inputs but must not silently solve');
  await page.getByTestId('demand-source-status').filter({ hasText: '4 grades from captured live forecast / 2 manual grades' }).waitFor();
  assert.deepEqual(loaded.firm_demand.BR150, original.firm_demand.BR150);
  assert.deepEqual(loaded.forecast_residual.BR150B, original.forecast_residual.BR150B);
  assert.deepEqual(loaded.firm_demand.BR150B, original.firm_demand.BR150B);
  assert.deepEqual(loaded.raw_prices, original.raw_prices);
  assert.equal(loaded.opening_raw_tons, 2000);
  for (const g of loaded.demand_source.grades) {
    const horizon = Math.max(...g.months.map(m => m.horizon_step));
    const response = await page.request.get(api + '/api/v1/forecast?product_id=' + encodeURIComponent(g.product_id) + '&horizon_months=' + horizon);
    assert.equal(response.status(), 200);
    const actualForecast = await response.json();
    assert.equal(actualForecast.model_name, g.model_name);
    assert.equal(actualForecast.trained_through, g.trained_through);
    for (const m of g.months) {
      assert.equal(actualForecast.periods[m.horizon_step - 1], m.period);
      assert.equal(actualForecast.forecast_tons[m.horizon_step - 1], m.point_tons, 'Point must match the actual existing forecast API');
      assert.equal(actualForecast.lower_tons[m.horizon_step - 1], m.lower_tons);
      assert.equal(actualForecast.upper_tons[m.horizon_step - 1], m.upper_tons);
      assert.equal(m.firm_window_tons + m.residual_window_tons, Math.max(m.firm_window_tons, m.target_window_tons));
    }
  }
  await page.locator('.joint-forecast-audit summary').click();
  assert.equal(await page.locator('.joint-forecast-audit tbody tr').count(), 4);
  await page.locator('.joint-forecast-source').screenshot({ path: path.join(out, 'demand-forecast-source-desktop.png') });
  const solve = async () => {
    const pending = page.waitForResponse(r => r.url().endsWith('/planning/integrated') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Solve integrated plan', exact: true }).click();
    const response = await pending; assert.equal(response.status(), 200);
    await page.getByText('Solved plan matches current inputs', { exact: true }).waitFor();
    return response.json();
  };
  const result = await solve();
  assert.equal(result.status, 'feasible');
  assert.equal(result.integration.demand_source_status, 'applied');
  assert.equal(result.integration.demand_tons, Object.values(loaded.firm_demand).flat().reduce((a, b) => a + b, 0) + Object.values(loaded.forecast_residual).flat().reduce((a, b) => a + b, 0));
  assert.deepEqual(solveRequests.at(-1).forecast_residual, loaded.forecast_residual);
  assert.equal(result.input.demand_source.snapshot_id, loaded.demand_source.snapshot_id);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export solved plan', exact: true }).click();
  const exported = JSON.parse(fs.readFileSync(await (await download).path(), 'utf8'));
  assert.equal(exported.input.demand_source.snapshot_id, loaded.demand_source.snapshot_id);
  await page.getByRole('spinbutton', { name: 'BR150 firm selected day', exact: true }).fill('101');
  await page.getByTestId('demand-source-status').filter({ hasText: 'Demand edited since forecast snapshot' }).waitFor();
  assert(await page.getByRole('button', { name: 'Solve integrated plan', exact: true }).isDisabled());
  assert(await page.getByRole('button', { name: 'Export solved plan', exact: true }).isDisabled());
  const edited = structuredClone(loaded); edited.firm_demand.BR150[0] = 101;
  const rejected = await page.request.post(api + '/api/v1/planning/integrated', { data: edited });
  assert.equal(rejected.status(), 422, 'Backend independently enforces reconciliation');
  const reconciled = await load();
  assert.equal(reconciled.firm_demand.BR150[0], 101);
  const m = reconciled.demand_source.grades.find(g => g.grade === 'BR150').months[0];
  assert.equal(m.firm_window_tons + m.residual_window_tons, Math.max(101, m.target_window_tons));
  assert(await page.getByRole('button', { name: 'Solve integrated plan', exact: true }).isEnabled());
  await page.getByRole('spinbutton', { name: 'BR150 forecast selected day', exact: true }).fill(String(reconciled.forecast_residual.BR150[0] + 1));
  await page.getByRole('button', { name: 'Accept edited demand as manual', exact: true }).click();
  const manual = await solve();
  assert.equal(manual.integration.demand_source_status, 'modified');
  assert.equal(manual.input.demand_source.manual_override_acknowledged, true);
  await page.getByRole('combobox', { name: 'Demand forecast path', exact: true }).selectOption('upper');
  const upper = await load();
  assert.equal(upper.demand_source.path, 'upper');
  assert.equal(upper.demand_source.status, 'applied');
  await page.locator('nav').getByRole('button', { name: 'Saved plans', exact: true }).click();
  await page.locator('nav').getByRole('button', { name: 'Integrated pilot', exact: false }).click();
  assert.equal(await page.getByRole('combobox', { name: 'Demand forecast path', exact: true }).inputValue(), 'upper');
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(500);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No document overflow');
  await page.locator('.joint-forecast-source').screenshot({ path: path.join(out, 'demand-forecast-source-mobile.png') });
  await page.setViewportSize({ width: 1680, height: 1100 });
  // Navigating while a load finishes must not strand the parent in a busy state.
  const delay = async route => { await new Promise(resolve => setTimeout(resolve, 600)); await route.continue(); };
  await page.route('**/planning/demand-forecast', delay);
  const delayed = page.waitForResponse(r => r.url().endsWith('/planning/demand-forecast') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Load real demand forecast', exact: true }).click();
  await page.locator('nav').getByRole('button', { name: 'Saved plans', exact: true }).click();
  assert.equal((await delayed).status(), 200);
  await page.locator('nav').getByRole('button', { name: 'Integrated pilot', exact: false }).click();
  await page.getByRole('button', { name: 'Load real demand forecast', exact: true }).waitFor();
  await page.waitForFunction(() => !Array.from(document.querySelectorAll('button')).find(b => b.textContent.includes('Load real demand forecast'))?.disabled);
  await page.unroute('**/planning/demand-forecast', delay);
  const beforeFailure = await page.getByTestId('demand-source-status').textContent();
  const unavailable = async route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Forecast unavailable test' }) });
  await page.route('**/planning/demand-forecast', unavailable);
  const failed = page.waitForResponse(r => r.url().endsWith('/planning/demand-forecast') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Load real demand forecast', exact: true }).click();
  assert.equal((await failed).status(), 503);
  await page.getByRole('alert').filter({ hasText: '503' }).waitFor();
  assert.equal(await page.getByTestId('demand-source-status').textContent(), beforeFailure, 'Failure keeps existing captured input, not fake forecasts');
  await page.unroute('**/planning/demand-forecast', unavailable);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', realForecastApiParity: true, fourMappedTwoManual: true, noDoubleCounting: true, actualSolverConsumption: true, provenanceExport: true, manualEditGuard: true, reconciliation: true, explicitManualOverride: true, navigationRace: true, unavailableNoFallback: true, desktopMobile: true }));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
