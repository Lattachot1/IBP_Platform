const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://localhost:3000';
const api = process.env.API_TEST_URL || 'http://127.0.0.1:8080';
const out = process.env.UI_TEST_OUTPUT || path.join(__dirname, '../../.ui-qa');
fs.mkdirSync(out, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ channel: process.env.UI_BROWSER || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 } });
  page.setDefaultTimeout(60000);
  const errors = [], requests = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (r.method() === 'POST' && r.url().includes('/api/v1/optimization/demo')) requests.push(r.postDataJSON()); });
  await page.goto(base + '/?view=lab');
  await page.getByText('Engine connected', { exact: true }).waitFor();
  await page.getByText('Results match current inputs', { exact: true }).waitFor();
  const rate = name => page.getByRole('spinbutton', { name: name + ' holding cost rate', exact: true });
  const apply = async () => {
    const pending = page.waitForResponse(r => r.url().includes('/api/v1/optimization/demo') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Apply priorities', exact: true }).click();
    const response = await pending; assert.equal(response.status(), 200);
    await page.getByText('Results match current inputs', { exact: true }).waitFor();
    return response.json();
  };
  assert.equal(await page.locator('.holding-rate-grid input').count(), 7);
  assert.equal(await rate('Raw material').inputValue(), '8');
  assert.equal(await rate('FG BR150').inputValue(), '13');
  await page.getByRole('button', { name: 'Set holding costs to 0', exact: true }).click();
  await page.getByText('Changes not applied', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Save snapshot', exact: true }).isDisabled());
  for (const input of await page.locator('.holding-rate-grid input').all()) assert.equal(await input.inputValue(), '0');
  const zero = await apply();
  assert.equal(zero.overtime_allowed, false);
  assert.equal(zero.selected_plan.cost_breakdown.finished_goods_holding, 0);
  assert.equal(zero.selected_plan.cost_breakdown.raw_material_holding, 0);
  assert.equal(zero.selected_plan.total_overtime_tons, 0);
  assert(zero.selected_plan.product_plan.some(p => p.expected_ending_inventory_tons > 0), 'Stock still tracked at zero rate');
  await page.getByTestId('comparison-confound').filter({ hasText: 'holding costs' }).waitFor();
  await rate('FG BR150').fill('25');
  await rate('FG BR150L').fill('30');
  await rate('Raw material').fill('4');
  const custom = await apply();
  assert.equal(custom.input.holding_costs.finished_goods.BR150, 25);
  assert.equal(custom.input.holding_costs.raw_material, 4);
  assert(custom.selected_plan.cost_breakdown.finished_goods_holding > 0);
  await page.getByRole('button', { name: 'Save snapshot', exact: true }).click();
  await rate('Raw material').fill('0');
  await page.locator('nav').getByRole('button', { name: 'Saved plans', exact: true }).click();
  const countBeforeRestore = requests.length;
  await page.getByRole('button', { name: 'Open', exact: true }).click();
  assert.equal(await rate('Raw material').inputValue(), '4');
  assert.equal(requests.length, countBeforeRestore, 'Current-model snapshot restores the tested result');
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export plan', exact: true }).click();
  const exported = JSON.parse(fs.readFileSync(await (await downloadEvent).path(), 'utf8'));
  assert.deepEqual(exported.input.holding_costs, custom.input.holding_costs);
  assert.equal(exported.selected_plan.overtime_allowed, false);
  await rate('Raw material').fill('0');
  const cohortStart = requests.length;
  await page.getByRole('button', { name: 'Run sensitivity', exact: true }).click();
  await page.getByTestId('sensitivity-status').filter({ hasText: 'Experiment complete' }).waitFor({ timeout: 180000 });
  for (const request of requests.slice(cohortStart)) assert.deepEqual(request.holding_costs, custom.input.holding_costs, 'Pending rates excluded from sensitivity');
  await page.getByRole('button', { name: 'Restore demo holding rates', exact: true }).click();
  assert.equal(await rate('Raw material').inputValue(), '8');
  assert.equal(await rate('FG BR150').inputValue(), '13');
  await page.locator('.holding-cost-controls').screenshot({ path: path.join(out, 'holding-costs-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(500);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No page overflow');
  await page.locator('.holding-cost-controls').screenshot({ path: path.join(out, 'holding-costs-mobile.png') });
  for (const strategy of ['deterministic', 'stochastic', 'robust']) {
    const response = await page.request.post(api + '/api/v1/optimization/demo', { data: { ...zero.input, strategy, demand_adjustment_pct: 30, capacity_adjustment_pct: -15, objective_weights: { ...zero.input.objective_weights, overtime: 20 } } });
    assert.equal(response.status(), 200);
    const result = await response.json();
    assert.equal(result.selected_plan.total_overtime_tons, 0);
    assert.equal(result.input.objective_weights.overtime, 0);
    for (const m of result.selected_plan.monthly_plan) assert(m.planned_production_tons <= 5800 * 0.85 + 0.1);
  }
  const invalid = await page.request.post(api + '/api/v1/optimization/demo', { data: { ...zero.input, holding_costs: { raw_material: -1 } } });
  assert.equal(invalid.status(), 422);
  const legacy = await page.request.post(api + '/api/simulate', { data: { base_demand: 10000, demand_change_pct: 20, enable_ot: true } });
  const legacyResult = await legacy.json();
  assert.equal(legacyResult.capacity_limit, 10500); assert.equal(legacyResult.enable_ot, false);
  // Retain the saved record, but make it resemble an older OT-capable model.
  await page.evaluate(() => {
    const key = 'ube.planning.saved-runs.v1'; const saved = JSON.parse(localStorage.getItem(key));
    saved[0].result.overtime_allowed = true;
    saved[0].result.selected_plan.total_overtime_tons = 900;
    saved[0].result.model_signature = 'old-ot-model';
    localStorage.setItem(key, JSON.stringify(saved));
  });
  await page.setViewportSize({ width: 1680, height: 1100 });
  await page.reload(); await page.getByText('Results match current inputs', { exact: true }).waitFor();
  await page.locator('nav').getByRole('button', { name: 'Saved plans', exact: true }).click();
  const rerun = page.waitForResponse(r => r.url().includes('/api/v1/optimization/demo') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Open', exact: true }).click();
  const restored = await (await rerun).json();
  assert.equal(restored.overtime_allowed, false); assert.equal(restored.selected_plan.total_overtime_tons, 0);
  assert.equal(restored.input.holding_costs.raw_material, 4);
  await page.goto(base + '/classic');
  assert.equal(await page.locator('#enableOTCheckbox').count(), 0);
  assert.equal(await page.getByRole('button', { name: /Add Overtime/ }).count(), 0);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', holdingRates: 7, zeroRates: true, saveRestoreExport: true, frozenRates: true, noOtAllStrategies: true, legacyOtSnapshotRerun: true, legacySimulatorNoOt: true, desktopMobile: true }));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
