const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://localhost:3000';
const out = path.join(__dirname, '../../.ui-qa');
fs.mkdirSync(out, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 }, acceptDownloads: true });
  page.setDefaultTimeout(90000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  for (let i = 0; i < 90; i++) {
    try { if ((await page.request.get('http://127.0.0.1:8080/api/health', { timeout: 1000 })).ok()) break; } catch {}
    await new Promise(r => setTimeout(r, 1000));
  }
  const loaded = page.waitForResponse(r => r.url().includes('/api/v1/plant/schedule') && r.request().method() === 'POST', { timeout: 180000 });
  await page.goto(base + '/?view=factory');
  const response = await loaded;
  assert.equal(response.status(), 200);
  const solved = await response.json();
  page.setDefaultTimeout(15000);
  assert.equal(solved.mode, 'cspat');
  assert.equal(solved.status, 'feasible');
  await page.getByRole('heading', { name: 'Factory Schedule', exact: true }).waitFor();
  await page.getByRole('button', { name: /Edit plan/ }).waitFor({ state: 'visible' });
  assert(await page.getByRole('button', { name: /Edit plan/ }).isEnabled());
  assert.equal(await page.locator('.opt-root .opt-ghead .opt-d').count(), 28);
  assert.equal(await page.locator('.opt-root .opt-grow .opt-glabel').count(), 5);
  await page.screenshot({ path: path.join(out, 'factory-desktop.png'), fullPage: true });
  const evaluate = page.waitForResponse(r => r.url().includes('/api/v1/plant/evaluate'));
  await page.getByRole('button', { name: /Edit plan/ }).click();
  const evaluated = await (await evaluate).json();
  assert.equal(evaluated.conflicts, 0);
  await page.locator('.opt-editrow [role=button]').first().click();
  const newEvaluation = page.waitForResponse(r => r.url().includes('/api/v1/plant/evaluate'));
  await page.getByRole('combobox', { name: 'Campaign grade', exact: true }).selectOption('VCR617');
  const bad = await (await newEvaluation).json();
  assert(bad.conflicts > 0, 'Illegal initial grade or transition must be flagged');
  await page.locator('.opt-checks li.conflict').first().waitFor();
  await page.screenshot({ path: path.join(out, 'factory-manual-conflicts.png'), fullPage: true });
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const exported = await download;
  const json = JSON.parse(fs.readFileSync(await exported.path(), 'utf8'));
  assert.equal(json.status, 'prototype_not_factory_approved');
  assert.equal(json.result.status, 'conflicts');
  await page.route('**/api/v1/plant/evaluate', r => r.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"checker unavailable"}' }));
  await page.locator('.opt-editrow [role=button]').first().click();
  await page.getByRole('combobox', { name: 'Campaign grade', exact: true }).selectOption('BR150B');
  await page.getByText(/Rule check failed/).first().waitFor();
  assert(await page.getByText('Editing / unverified', { exact: true }).isVisible());
  assert(await page.getByRole('button', { name: 'Export', exact: true }).isDisabled());
  await page.unroute('**/api/v1/plant/evaluate');
  await page.getByRole('button', { name: 'Exit edit mode', exact: true }).click();
  await page.getByRole('button', { name: 'Shared stock & delivery sandbox', exact: true }).click();
  assert(new URL(page.url()).searchParams.get('view') === 'timeline');
  await page.getByRole('button', { name: 'Factory schedule', exact: true }).first().click();
  assert(await page.getByRole('heading', { name: 'Factory Schedule', exact: true }).isVisible());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForFunction(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 1);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(out, 'factory-mobile.png'), fullPage: true });
  await page.screenshot({ path: path.join(out, 'factory-mobile-viewport.png') });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No page-level mobile overflow');
  await page.setViewportSize({ width: 1680, height: 1100 });
  await page.getByRole('button', { name: 'Use monthly production targets', exact: true }).click();
  await page.getByText('Inputs changed since the last solve', { exact: false }).waitFor();
  assert.equal(await page.locator('#opt-horizon').inputValue(), '61');
  assert(await page.getByRole('button', { name: 'Export', exact: true }).isDisabled());
  assert(await page.getByRole('button', { name: /Edit plan/ }).isDisabled());
  await page.route('**/api/v1/plant/schedule', r => r.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"solver unavailable"}' }));
  await page.getByRole('button', { name: /Run optimization \(inputs changed\)/ }).click();
  await page.getByText(/backend answered HTTP 503/).waitFor();
  assert(await page.getByRole('button', { name: /Edit plan/ }).isDisabled());
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', realSolver: true, manualValidation: true, export: true, navigation: true, mobile: true, monthlyTargets: true, dependencyFailure: true }));
  await browser.close();
})().catch(async e => { console.error(e); if (browser) await browser.close(); process.exit(1); });
