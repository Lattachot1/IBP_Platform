const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.UI_TEST_URL || 'http://localhost:3000';
const api = process.env.API_TEST_URL || 'http://127.0.0.1:8080';
const out = process.env.UI_TEST_OUTPUT || path.join(__dirname, '../../.ui-qa');
fs.mkdirSync(out, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ channel: process.env.UI_BROWSER || 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1680, height: 1100 } });
  page.setDefaultTimeout(60000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/?view=integrated');
  await page.getByText('Inputs ready / no joint plan solved yet', { exact: true }).waitFor();
  await page.getByRole('spinbutton', { name: 'Solve budget (s)', exact: true }).fill('5');
  const solve = async () => {
    const pending = page.waitForResponse(r => r.url().includes('/api/v1/planning/integrated') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Solve integrated plan', exact: true }).click();
    const response = await pending; assert.equal(response.status(), 200);
    return response.json();
  };
  const first = await solve();
  assert.equal(first.status, 'feasible');
  assert.equal(first.mode, 'integrated_cpsat');
  await page.getByText('Solved plan matches current inputs', { exact: true }).waitFor();
  assert.equal(await page.locator('.joint-gantt-row').count(), 10);
  assert(await page.locator('.joint-chart .recharts-line-curve').count() >= 3);
  await page.getByRole('button', { name: 'Freeze solved day', exact: true }).click();
  await page.getByRole('button', { name: 'Freeze purchase', exact: true }).click();
  await page.getByText('Inputs changed / previous plan is not current', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: 'Export solved plan', exact: true }).isDisabled());
  const locked = await solve();
  assert.equal(locked.status, 'feasible');
  assert.equal(locked.integration.locks_honored.production_days, 1);
  assert.equal(locked.integration.locks_honored.purchase_days, 1);
  assert.deepEqual(locked.days[0].parts, first.days[0].parts);
  assert.equal(locked.integration.daily[0].purchase_tons, first.integration.daily[0].purchase_tons);
  await page.getByTestId('joint-before-after').waitFor();
  assert(await page.locator('.joint-ghost').count() > 0);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export solved plan', exact: true }).click();
  const exported = JSON.parse(fs.readFileSync(await (await download).path(), 'utf8'));
  assert.equal(exported.overtime_allowed, false);
  assert.equal(exported.input.day_locks.length, 1);
  await page.getByRole('combobox', { name: 'Locked integrated grade', exact: true }).selectOption('BR150L');
  const invalid = await solve();
  assert.equal(invalid.status, 'infeasible');
  await page.getByRole('alert').filter({ hasText: 'infeasible' }).waitFor();
  assert.equal(await page.locator('.joint-gantt-row').count(), 10, 'Prior solved plan retained after conflict');
  assert(await page.getByRole('button', { name: 'Export solved plan', exact: true }).isDisabled());
  await page.getByRole('button', { name: 'Clear all locks', exact: true }).click();
  assert.equal(await page.getByRole('alert').filter({ hasText: 'infeasible' }).count(), 0, 'Prior input error clears after changing locks');
  // Import a small exact fixture to verify the full lexicographic path quickly.
  const demo = await (await page.request.get(api + '/api/v1/planning/pilot?horizon_days=7')).json();
  demo.plant.start_date = '2026-10-26'; demo.plant.time_limit_s = 5;
  demo.plant.initial = { grade: 'BR150', remain_days: 7, rx12_age: 0, rx34_age: 0, vcr_elapsed_days: 0 };
  demo.opening_fg = Object.fromEntries(Object.keys(demo.opening_fg).map(g => [g, 0]));
  demo.opening_raw_tons = 0; demo.purchase_lead_days = 0; demo.purchase_limit_tons_per_day = 2000; demo.raw_pipeline = [];
  for (const g of Object.keys(demo.opening_fg)) { demo.firm_demand[g] = Array(7).fill(g === 'BR150' ? 200 : 0); demo.forecast_residual[g] = Array(7).fill(0); }
  demo.raw_prices = [1000, ...Array(6).fill(2000)];
  const imported = page.waitForResponse(r => r.url().includes('/api/v1/planning/validate') && r.request().method() === 'POST');
  await page.locator('.joint-pilot input[type=file]').setInputFiles({ name: 'pilot-input.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(demo)) });
  assert.equal((await imported).status(), 200);
  await page.getByRole('combobox', { name: 'Integrated objective policy', exact: true }).selectOption('delivery_first');
  await page.locator('.joint-inputs summary').click();
  await page.getByRole('button', { name: 'Set holding costs to 0', exact: true }).click();
  const lex = await solve();
  assert.equal(lex.integration.shortage_tons, 600);
  assert.equal(lex.integration.closing_wip_tons, 690);
  assert.equal(lex.integration.cost_breakdown.finished_goods_holding, 0);
  assert.equal(lex.integration.cost_breakdown.raw_material_holding, 0);
  assert.equal(lex.integration.stages.length, 2);
  assert.equal(lex.integration.optimality_proven, true);
  await page.locator('.joint-inputs summary').click();
  await page.locator('.joint-audit summary').click();
  assert(await page.getByText('shortage_tons', { exact: true }).isVisible());
  await page.locator('.joint-pilot').screenshot({ path: path.join(out, 'integrated-pilot-desktop.png') });
  await page.locator('nav').getByRole('button', { name: 'Factory schedule', exact: true }).click();
  await page.locator('nav').getByRole('button', { name: 'Integrated pilot', exact: false }).click();
  assert.equal(await page.getByRole('combobox', { name: 'Integrated objective policy', exact: true }).inputValue(), 'delivery_first');
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(600);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No document overflow');
  await page.locator('.joint-pilot').screenshot({ path: path.join(out, 'integrated-pilot-mobile.png') });
  await page.setViewportSize({ width: 1680, height: 1100 });
  await page.getByRole('button', { name: 'Copy monthly assumptions', exact: true }).click();
  await page.getByText(/Copied monthly demo totals/).waitFor();
  await page.getByRole('button', { name: 'Export input JSON', exact: true }).waitFor();
  const inputDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export input JSON', exact: true }).click();
  const copied = JSON.parse(fs.readFileSync(await (await inputDownload).path(), 'utf8'));
  assert.equal(copied.plant.horizon_days, 61);
  assert.equal(copied.plant.start_date, '2026-09-01');
  assert(Object.values(copied.firm_demand).every(values => values.every(x => x === 0)));
  const validation = await page.request.post(api + '/api/v1/planning/validate', { data: copied });
  assert.equal(validation.status(), 200);
  const rejected = await page.request.post(api + '/api/v1/planning/validate', { data: { ...copied, weights: { overtime: 10 } } });
  assert.equal(rejected.status(), 422);
  const offline = async route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Solver unavailable test' }) });
  await page.route('**/api/v1/planning/integrated', offline);
  await solve().catch(e => { assert.match(e.message, /503/); });
  await page.getByRole('alert').filter({ hasText: '503' }).waitFor();
  await page.unroute('**/api/v1/planning/integrated', offline);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ status: 'passed', jointSolver: true, hardLocks: true, ghostComparison: true, conflictRetainsPlan: true, importsExports: true, lexicalProof: true, zeroHoldingCosts: true, monthlyAssumptionCopy: true, unavailableNotSample: true, navigationAndMobile: true }));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
